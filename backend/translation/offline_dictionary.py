def get_offline_translation(text: str, target_lang: str) -> str | None:
    """
    Look up direct translation for word or short sentence.
    """
    cleaned = text.strip().upper().replace(" ", "_")
    lang = target_lang.lower()
    if cleaned in OFFLINE_DICTIONARY and lang in OFFLINE_DICTIONARY[cleaned]:
        return OFFLINE_DICTIONARY[cleaned][lang]
    return None
